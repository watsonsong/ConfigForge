pub const LANGUAGE: &str = "rust";

#[derive(Debug, Clone, Default, Deserialize, Serialize, PartialEq, Eq)]
pub struct RustCodegenOptions {
    #[serde(default)]
    pub derive_serde: bool,
    #[serde(default)]
    pub runtime_interface: RuntimeInterfaceMode,
    #[serde(default)]
    pub runtime_core_path: Option<String>,
}

pub(crate) struct RustCodeGenerator;

impl CodeGenerator for RustCodeGenerator {
    fn language(&self) -> &'static str {
        LANGUAGE
    }

    fn default_naming(&self) -> NamingConfig {
        NamingConfig {
            type_name: CaseStyle::PascalCase,
            enum_value: CaseStyle::PascalCase,
            field: CaseStyle::SnakeCase,
            function: CaseStyle::SnakeCase,
            constant: CaseStyle::ScreamingSnakeCase,
        }
    }

    fn default_formatting(&self) -> CodeWriterConfig {
        CodeWriterConfig::default().with_indent_width(4)
    }

    #[cfg(test)]
    fn generate(&self, input: &CodeExportInput<'_>) -> Result<Vec<super::GeneratedFile>> {
        let mut content = super::CodeWriter::new(input.target.options.formatting);
        render_rust_code(self, &mut content, input)?;
        Ok(vec![super::GeneratedFile {
            path: rust_output_path(input),
            content: content.finish(),
        }])
    }

    fn generate_to_sink(&self, input: &CodeExportInput<'_>, sink: &ArtifactSink) -> Result<()> {
        let output_path = rust_output_path(input);
        let stream = sink.create(output_path.clone())?;
        let mut content = CheckedStreamingCodeWriter::new(stream, input.target.options.formatting);
        render_rust_code(self, &mut content, input)?;
        let stream = content
            .finish()
            .map_err(|source| ConfigForgeError::WriteFile {
                path: output_path,
                source,
            })?;
        stream.finish().map(|_| ())
    }
}

fn rust_output_path(input: &CodeExportInput<'_>) -> std::path::PathBuf {
    input
        .target
        .out_dir
        .join(input.target.single_file_name("generated", "rs"))
}

fn write_file_header(
    generator: &dyn CodeGenerator,
    content: &mut impl CodeWriterLike,
    input: &CodeExportInput<'_>,
) {
    if let Some(template) = &input.target.options.file_header {
        let project = &input.project;
        let mut output = template.to_owned();
        output = output.replace("{{project.name}}", project.name.as_deref().unwrap_or(""));
        output = output.replace("{{project.desc}}", project.desc.as_deref().unwrap_or(""));
        output = output.replace(
            "{{project.copyright}}",
            project.copyright.as_deref().unwrap_or(""),
        );
        output = output.replace("{{datetime}}", &input.generated_at);
        if !output.ends_with('\n') {
            output.push('\n');
        }
        content.raw(output);
        return;
    }

    let prefix = generator.line_comment_prefix();
    content.line(format!(
        "{prefix} Copyright (c) 2026 ConfigForge contributors"
    ));
    content.line(format!("{prefix} SPDX-License-Identifier: Apache-2.0"));
    content.blank_line();
    content.line(format!("{prefix} Generated by config-forge. Do not edit."));
}

fn render_rust_code(
    generator: &RustCodeGenerator,
    content: &mut impl CodeWriterLike,
    input: &CodeExportInput<'_>,
) -> Result<()> {
    let model = build_code_model(input.meta, &input.target_tags, &input.runtime_data_files)?;
    require_non_empty_index_fields(&model)?;
    let rust_options = input
        .target
        .options
        .language_options::<RustCodegenOptions>(LANGUAGE)?;
    validate_runtime_interface_options(&rust_options)?;
    let names = RustNames::new(&input.target.options);
    validate_generated_symbols(&model, &names)?;
    write_file_header(generator, content, input);
    content.raw("use std::{cell::{Cell, OnceCell, RefCell}, collections::HashMap};\n\n");
    render_runtime_reader_contract(content, &rust_options);
    render_runtime_reader_helpers(content);
    render_rust_i18n_prelude(content, &input.target.options.i18n);
    content.raw(concat!(
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n",
        "enum LinkCache {\n",
        "    Unresolved,\n",
        "    Empty,\n",
        "    RowIndex(usize),\n",
        "}\n\n",
        "impl Default for LinkCache {\n",
        "    fn default() -> Self { Self::Unresolved }\n",
        "}\n\n",
        "#[derive(Debug, Clone, PartialEq, Eq, Default)]\n",
        "struct LinkListCache {\n",
        "    row_indexes: Option<Vec<usize>>,\n",
        "}\n\n",
    ));

    for code_enum in &model.enums {
        push_doc(content, code_enum.desc.as_deref(), "/// ");
        push_derive(
            content,
            "Debug, Clone, PartialEq, Eq, Hash",
            rust_options.derive_serde,
        );
        content.raw_fmt(format_args!(
            "pub enum {} {{\n",
            names.type_name(&code_enum.name)?
        ));
        for value in &code_enum.values {
            push_doc(content, value.desc.as_deref(), "    /// ");
            if rust_options.derive_serde {
                content.raw_fmt(format_args!("    #[serde(rename = {:?})]\n", value.name));
            }
            content.raw_fmt(format_args!(
                "    {},\n",
                names.enum_variant_name(&value.name)?
            ));
        }
        content.raw("}\n\n");
        render_enum_reader_impl(content, code_enum, &names)?;
    }

    for code_struct in &model.structs {
        push_doc(content, code_struct.desc.as_deref(), "/// ");
        push_derive(
            content,
            "Debug, Clone, PartialEq",
            rust_options.derive_serde,
        );
        content.raw_fmt(format_args!(
            "pub struct {} {{\n",
            names.type_name(&code_struct.name)?
        ));
        for field in &code_struct.fields {
            push_doc(content, field.desc.as_deref(), "    /// ");
            if rust_options.derive_serde {
                content.raw_fmt(format_args!("    #[serde(rename = {:?})]\n", field.name));
            }
            content.raw_fmt(format_args!(
                "    pub {}: {},\n",
                names.field_name(&field.name)?,
                names.rust_field_type(field)?
            ));
        }
        content.raw("}\n\n");
        render_struct_reader_impl(content, code_struct, &names)?;
        render_rust_text_helpers(
            content,
            &names.type_name(&code_struct.name)?,
            &code_struct.name,
            &code_struct.fields,
            &names,
            &input.target.options.i18n,
        )?;
    }

    for table in &model.tables {
        for fragment in &table.fragments {
            if matches!(fragment.payload, CodeFragmentPayload::Struct { .. }) {
                continue;
            }
            push_doc(content, fragment.desc.as_deref(), "/// ");
            push_derive(
                content,
                "Debug, Clone, PartialEq",
                rust_options.derive_serde,
            );
            content.raw_fmt(format_args!(
                "pub struct {} {{\n",
                names.fragment_type_name(&table.name, &fragment.name)?
            ));
            for field in &fragment.fields {
                push_doc(content, field.desc.as_deref(), "    /// ");
                if rust_options.derive_serde {
                    content.raw_fmt(format_args!("    #[serde(rename = {:?})]\n", field.name));
                }
                content.raw_fmt(format_args!(
                    "    pub {}: {},\n",
                    names.field_name(&field.name)?,
                    names.rust_field_type(field)?
                ));
            }
            content.raw("}\n\n");
            render_fragment_reader_impl(content, table, fragment, &names)?;
            render_rust_text_helpers(
                content,
                &names.fragment_type_name(&table.name, &fragment.name)?,
                &format!("{}.{}", table.name, fragment.name),
                &fragment.fields,
                &names,
                &input.target.options.i18n,
            )?;
        }
    }

    for table in &model.tables {
        push_doc(content, table.desc.as_deref(), "/// ");
        push_derive(
            content,
            "Debug, Clone, PartialEq",
            rust_options.derive_serde,
        );
        content.raw_fmt(format_args!(
            "pub struct {} {{\n",
            names.row_type_name(&table.name)?
        ));
        for field in &table.fields {
            push_doc(content, field.desc.as_deref(), "    /// ");
            if rust_options.derive_serde {
                content.raw_fmt(format_args!("    #[serde(rename = {:?})]\n", field.name));
            }
            content.raw_fmt(format_args!(
                "    pub {}: {},\n",
                names.field_name(&field.name)?,
                names.rust_field_type(field)?
            ));
        }
        for fragment in &table.fragments {
            if rust_options.derive_serde {
                content.raw_fmt(format_args!("    #[serde(rename = {:?})]\n", fragment.name));
            }
            content.raw_fmt(format_args!(
                "    pub {}: Option<{}>,\n",
                names.field_name(&fragment.name)?,
                names.fragment_payload_type_name(table, fragment)?
            ));
        }
        for foreign_key in table
            .foreign_keys
            .iter()
            .filter(|foreign_key| foreign_key.linked_field.is_some())
        {
            let cache_type = match foreign_key
                .linked_field
                .as_ref()
                .expect("linked field")
                .cardinality
            {
                super::ir::CodeRelationCardinality::Many => "RefCell<LinkListCache>",
                _ => "Cell<LinkCache>",
            };
            if rust_options.derive_serde {
                content.raw("    #[serde(skip, default)]\n");
            }
            content.raw_fmt(format_args!(
                "    {}: {},\n",
                names.relation_cache_field_name(foreign_key)?,
                cache_type
            ));
        }
        content.raw("}\n\n");
        render_row_reader_impl(content, table, &names)?;
        content.raw_fmt(format_args!(
            "impl {} {{\n",
            names.row_type_name(&table.name)?
        ));
        render_rust_text_helper_methods(
            content,
            &table.name,
            &table.fields,
            &names,
            &input.target.options.i18n,
        )?;
        for fragment in &table.fragments {
            content.raw_fmt(format_args!(
                "    pub fn has_{}(&self) -> bool {{ self.{}.is_some() }}\n",
                names.field_name(&fragment.name)?,
                names.field_name(&fragment.name)?
            ));
            content.raw_fmt(format_args!(
                "    pub fn {}(&self) -> Option<&{}> {{ self.{}.as_ref() }}\n",
                names.field_name(&fragment.name)?,
                names.fragment_payload_type_name(table, fragment)?,
                names.field_name(&fragment.name)?
            ));
        }
        render_row_relation_methods(content, &model, table, &names)?;
        content.raw("}\n\n");
        render_table(content, table, &names)?;
    }

    content.raw("pub trait GameDataAccess {\n");
    for table in &model.tables {
        content.raw_fmt(format_args!(
            "    fn {}(&self) -> RuntimeDataResult<&{}>;\n",
            names.field_name(&table.name)?,
            names.table_data_type_name(table)?
        ));
    }
    content.raw("}\n\n");

    content.raw("pub struct GameData {\n");
    for table in &model.tables {
        content.raw_fmt(format_args!(
            "    pub {}: {},\n",
            names.field_name(&table.name)?,
            names.table_data_type_name(table)?
        ));
    }
    content.raw("}\n\n");
    content.raw("impl GameData {\n");
    content.raw("    pub fn load(loader: &impl RuntimeDataLoader) -> RuntimeDataResult<Self> {\n");
    content.raw("        Ok(Self {\n");
    for table in &model.tables {
        content.raw_fmt(format_args!(
            "            {}: {}::load(loader)?,\n",
            names.field_name(&table.name)?,
            names.table_data_type_name(table)?
        ));
    }
    content.raw("        })\n");
    content.raw("    }\n");
    render_game_data_link_methods(content, &model, &names)?;
    content.raw("}\n");

    content.raw("\nimpl GameDataAccess for GameData {\n");
    for table in &model.tables {
        content.raw_fmt(format_args!(
            "    fn {}(&self) -> RuntimeDataResult<&{}> {{ Ok(&self.{}) }}\n",
            names.field_name(&table.name)?,
            names.table_data_type_name(table)?,
            names.field_name(&table.name)?
        ));
    }
    content.raw("}\n\n");

    content.raw("pub struct LazyGameData<L: RuntimeDataLoader> {\n");
    content.raw("    loader: L,\n");
    for table in &model.tables {
        content.raw_fmt(format_args!(
            "    {}: OnceCell<{}>,\n",
            names.field_name(&table.name)?,
            names.table_data_type_name(table)?
        ));
    }
    content.raw("}\n\n");
    content.raw("impl<L: RuntimeDataLoader> LazyGameData<L> {\n");
    content.raw("    pub fn new(loader: L) -> Self {\n");
    content.raw("        Self {\n");
    content.raw("            loader,\n");
    for table in &model.tables {
        content.raw_fmt(format_args!(
            "            {}: OnceCell::new(),\n",
            names.field_name(&table.name)?
        ));
    }
    content.raw("        }\n");
    content.raw("    }\n\n");
    for table in &model.tables {
        content.raw_fmt(format_args!(
                "    pub fn {}(&self) -> RuntimeDataResult<&{}> {{ <Self as GameDataAccess>::{}(self) }}\n\n",
                names.field_name(&table.name)?,
                names.table_data_type_name(table)?,
                names.field_name(&table.name)?
            ));
    }
    content.raw("    pub fn preload_all(&self) -> RuntimeDataResult<()> {\n");
    for table in &model.tables {
        content.raw_fmt(format_args!(
            "        let _ = self.{}()?;\n",
            names.field_name(&table.name)?
        ));
    }
    content.raw("        Ok(())\n");
    content.raw("    }\n");
    content.raw("\n    pub fn link_all(&self) -> RuntimeDataResult<()> {\n");
    content.raw("        self.preload_all()?;\n");
    for table in &model.tables {
        if table
            .foreign_keys
            .iter()
            .any(|foreign_key| foreign_key.linked_field.is_some())
        {
            content.raw_fmt(format_args!(
                "        self.{}()?.link(self)?;\n",
                names.field_name(&table.name)?
            ));
        }
    }
    content.raw("        Ok(())\n");
    content.raw("    }\n");
    content.raw("}\n\n");

    content.raw("impl<L: RuntimeDataLoader> GameDataAccess for LazyGameData<L> {\n");
    for table in &model.tables {
        content.raw_fmt(format_args!(
            concat!(
                "    fn {}(&self) -> RuntimeDataResult<&{}> {{\n",
                "        if self.{}.get().is_none() {{\n",
                "            let value = {}::load(&self.loader)?;\n",
                "            let _ = self.{}.set(value);\n",
                "        }}\n",
                "        self.{}.get().ok_or_else(|| RuntimeDataError::decode({:?}.to_owned()))\n",
                "    }}\n",
            ),
            names.field_name(&table.name)?,
            names.table_data_type_name(table)?,
            names.field_name(&table.name)?,
            names.table_data_type_name(table)?,
            names.field_name(&table.name)?,
            names.field_name(&table.name)?,
            format!("lazy table `{}` was not initialized", table.name)
        ));
    }
    content.raw("}\n");

    Ok(())
}

fn validate_runtime_interface_options(options: &RustCodegenOptions) -> Result<()> {
    if matches!(options.runtime_interface, RuntimeInterfaceMode::External) {
        validate_optional_runtime_path("runtime_core_path", &options.runtime_core_path)?;
    }
    Ok(())
}

fn validate_optional_runtime_path(kind: &str, value: &Option<String>) -> Result<()> {
    if let Some(value) = value {
        if value.trim().is_empty() || value.chars().any(char::is_control) {
            return Err(ConfigForgeError::Validation(format!(
                "invalid Rust {kind} `{value}`; value must be non-empty and single-line"
            )));
        }
    }
    Ok(())
}

fn render_rust_text_helpers(
    content: &mut impl CodeWriterLike,
    type_name: &str,
    context_prefix: &str,
    fields: &[CodeField],
    names: &RustNames<'_>,
    i18n: &I18nOptions,
) -> Result<()> {
    if !fields
        .iter()
        .any(|field| matches!(field.code_type, super::CodeTypeRef::Text))
    {
        return Ok(());
    }
    content.raw_fmt(format_args!("impl {type_name} {{\n"));
    render_rust_text_helper_methods(content, context_prefix, fields, names, i18n)?;
    content.raw("}\n\n");
    Ok(())
}

fn render_rust_i18n_prelude(content: &mut impl CodeWriterLike, i18n: &I18nOptions) {
    match i18n.mode {
        I18nMode::Generic => content.raw(concat!(
            "pub trait TextTranslator {\n",
            "    fn translate(&self, msgctxt: Option<&str>, msgid: &str) -> Option<String>;\n",
            "}\n\n",
        )),
        I18nMode::GlobalFunction => {}
    }
}

fn render_rust_text_helper_methods(
    content: &mut impl CodeWriterLike,
    context_prefix: &str,
    fields: &[CodeField],
    names: &RustNames<'_>,
    i18n: &I18nOptions,
) -> Result<()> {
    for field in fields
        .iter()
        .filter(|field| matches!(field.code_type, super::CodeTypeRef::Text))
    {
        let function_name = names.text_function_name(&field.name)?;
        let field_name = names.field_name(&field.name)?;
        let context = format!("{context_prefix}.{}", field.name);
        match i18n.mode {
            I18nMode::Generic if field.required => {
                content.raw_fmt(format_args!(
                    concat!(
                        "    pub fn {function_name}(&self, translator: &impl TextTranslator) -> String {{\n",
                        "        translator.translate(Some({context:?}), &self.{field_name}).unwrap_or_else(|| self.{field_name}.clone())\n",
                        "    }}\n",
                    ),
                    function_name = function_name,
                    context = context,
                    field_name = field_name,
                ));
            }
            I18nMode::Generic => {
                content.raw_fmt(format_args!(
                    concat!(
                        "    pub fn {function_name}(&self, translator: &impl TextTranslator) -> Option<String> {{\n",
                        "        self.{field_name}.as_ref().map(|msgid| translator.translate(Some({context:?}), msgid).unwrap_or_else(|| msgid.clone()))\n",
                        "    }}\n",
                    ),
                    function_name = function_name,
                    context = context,
                    field_name = field_name,
                ));
            }
            I18nMode::GlobalFunction if field.required => {
                content.raw_fmt(format_args!(
                    concat!(
                        "    pub fn {function_name}(&self) -> String {{\n",
                        "        {expr}\n",
                        "    }}\n",
                    ),
                    function_name = function_name,
                    expr = rust_global_i18n_expr(
                        i18n,
                        &context,
                        &format!("&self.{field_name}"),
                        &format!("self.{field_name}.clone()")
                    ),
                ));
            }
            I18nMode::GlobalFunction => {
                content.raw_fmt(format_args!(
                    concat!(
                        "    pub fn {function_name}(&self) -> Option<String> {{\n",
                        "        self.{field_name}.as_ref().map(|msgid| {expr})\n",
                        "    }}\n",
                    ),
                    function_name = function_name,
                    field_name = field_name,
                    expr = rust_global_i18n_expr(i18n, &context, "msgid", "msgid.clone()"),
                ));
            }
        }
    }
    Ok(())
}

fn rust_global_i18n_expr(
    i18n: &I18nOptions,
    context: &str,
    msgid_expr: &str,
    fallback_expr: &str,
) -> String {
    let function = i18n.function.as_deref().expect("global i18n function");
    match i18n.returns {
        I18nFunctionReturn::String => {
            format!("{function}(Some({context:?}), {msgid_expr}).into()")
        }
        I18nFunctionReturn::Optional => {
            format!(
                "{function}(Some({context:?}), {msgid_expr}).unwrap_or_else(|| {fallback_expr})"
            )
        }
    }
}

fn push_doc(content: &mut impl CodeWriterLike, desc: Option<&str>, prefix: &str) {
    if let Some(desc) = desc {
        for line in desc.lines() {
            content.raw(prefix);
            content.raw(line);
            content.newline();
        }
    }
}

fn push_derive(content: &mut impl CodeWriterLike, base_derives: &str, derive_serde: bool) {
    if derive_serde {
        content.raw_fmt(format_args!(
            "#[derive({base_derives}, serde::Serialize, serde::Deserialize)]\n"
        ));
    } else {
        content.raw_fmt(format_args!("#[derive({base_derives})]\n"));
    }
}
