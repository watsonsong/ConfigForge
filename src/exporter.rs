use std::{fs, path::Path};

use serde::Serialize;

use crate::{
    meta::{MetaSet, TableMeta},
    source::DataTable,
    validation::validate_table,
    ConfigForgeError, Result,
};

#[derive(Debug, Clone)]
pub struct ExportOptions<'a> {
    pub meta_path: &'a Path,
    pub data_dir: &'a Path,
    pub out_dir: &'a Path,
}

#[derive(Debug, Clone, Serialize)]
struct ExportedTable<'a> {
    meta: &'a TableMeta,
    rows: &'a [crate::source::DataRow],
}

pub fn validate_project(meta_path: &Path, data_dir: &Path) -> Result<()> {
    let meta_set = MetaSet::from_path(meta_path)?;
    for table_meta in &meta_set.tables {
        let table = load_table(data_dir, table_meta)?;
        validate_table(table_meta, &table)?;
    }
    Ok(())
}

pub fn export_project(options: ExportOptions<'_>) -> Result<()> {
    let meta_set = MetaSet::from_path(options.meta_path)?;
    fs::create_dir_all(options.out_dir).map_err(|source| ConfigForgeError::WriteFile {
        path: options.out_dir.to_path_buf(),
        source,
    })?;

    for table_meta in &meta_set.tables {
        let table = load_table(options.data_dir, table_meta)?;
        validate_table(table_meta, &table)?;
        write_table_json(options.out_dir, table_meta, &table)?;
        write_table_rust_stub(options.out_dir, table_meta)?;
    }

    Ok(())
}

fn load_table(data_dir: &Path, table_meta: &TableMeta) -> Result<DataTable> {
    DataTable::from_csv_path(&table_meta.name, data_dir.join(&table_meta.source))
}

fn write_table_json(out_dir: &Path, table_meta: &TableMeta, table: &DataTable) -> Result<()> {
    let payload = ExportedTable {
        meta: table_meta,
        rows: &table.rows,
    };
    let content = serde_json::to_string_pretty(&payload)?;
    let path = out_dir.join(format!("{}.json", table_meta.name));
    fs::write(&path, content).map_err(|source| ConfigForgeError::WriteFile { path, source })
}

fn write_table_rust_stub(out_dir: &Path, table_meta: &TableMeta) -> Result<()> {
    let struct_name = to_pascal_case(&table_meta.name);
    let mut fields = String::new();
    for field in &table_meta.fields {
        fields.push_str(&format!(
            "    pub {}: {},\n",
            field.name,
            rust_type_name(&field.field_type)
        ));
    }

    let content = format!(
        "// Generated by config_forge.\n#[derive(Debug, Clone)]\npub struct {struct_name} {{\n{fields}}}\n"
    );
    let path = out_dir.join(format!("{}.rs", table_meta.name));
    fs::write(&path, content).map_err(|source| ConfigForgeError::WriteFile { path, source })
}

fn rust_type_name(field_type: &crate::meta::FieldType) -> &'static str {
    match field_type {
        crate::meta::FieldType::String => "String",
        crate::meta::FieldType::I64 => "i64",
        crate::meta::FieldType::F64 => "f64",
        crate::meta::FieldType::Bool => "bool",
    }
}

fn to_pascal_case(value: &str) -> String {
    value
        .split(|ch: char| !ch.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

#[cfg(test)]
