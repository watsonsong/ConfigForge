use std::path::PathBuf;

use crate::{
    ConfigForgeError, Result,
    artifact::{ArtifactSink, ArtifactWriteStream},
};

use super::{
    CheckedStreamingCodeWriter, CodeExportInput, CodeGenerator, CodeWriterConfig, CodeWriterLike,
};

pub(crate) fn write_file_header<G: CodeGenerator + ?Sized>(
    generator: &G,
    writer: &mut impl CodeWriterLike,
    input: &CodeExportInput<'_>,
) {
    if let Some(template) = &input.target.options.file_header {
        let project = &input.project;
        let mut output = template
            .replace("{{project.name}}", project.name.as_deref().unwrap_or(""))
            .replace("{{project.desc}}", project.desc.as_deref().unwrap_or(""))
            .replace(
                "{{project.copyright}}",
                project.copyright.as_deref().unwrap_or(""),
            )
            .replace("{{datetime}}", &input.generated_at);
        if !output.ends_with('\n') {
            output.push('\n');
        }
        writer.raw(output);
        return;
    }
    let prefix = generator.line_comment_prefix();
    writer.line(format!(
        "{prefix} Copyright (c) 2026 ConfigForge contributors"
    ));
    writer.line(format!("{prefix} SPDX-License-Identifier: Apache-2.0"));
    writer.blank_line();
    writer.line(format!("{prefix} Generated by config-forge. Do not edit."));
}

pub(crate) fn write_code_to_sink(
    sink: &ArtifactSink,
    path: PathBuf,
    formatting: CodeWriterConfig,
    render: impl FnOnce(&mut CheckedStreamingCodeWriter<ArtifactWriteStream>) -> Result<()>,
) -> Result<()> {
    let stream = sink.create(path.clone())?;
    let mut writer = CheckedStreamingCodeWriter::new(stream, formatting);
    render(&mut writer)?;
    let stream = writer
        .finish()
        .map_err(|source| ConfigForgeError::WriteFile { path, source })?;
    stream.finish().map(|_| ())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::artifact::{ArtifactWriteMode, ArtifactWriter};

    #[test]
    fn renderer_error_preserves_existing_temp_commit_output() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("generated.rs");
        std::fs::write(&path, "original").unwrap();
        let sink = ArtifactWriter::new(ArtifactWriteMode::TempCommit).open_sink();
        let error =
            write_code_to_sink(&sink, path.clone(), CodeWriterConfig::default(), |writer| {
                writer.raw("partial replacement");
                Err(ConfigForgeError::WriteFile {
                    path: path.clone(),
                    source: std::io::Error::other("renderer failed"),
                })
            })
            .unwrap_err();
        assert!(error.to_string().contains("renderer failed"));
        assert!(sink.finish().is_err());
        assert_eq!(std::fs::read_to_string(path).unwrap(), "original");
    }
}
